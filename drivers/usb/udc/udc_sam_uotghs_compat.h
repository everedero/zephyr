/** @file
 * @brief UOTGHS to USBHS compatibility definitions for the SAM3X series.
 *
 * The SAM3X UOTGHS and the SAM E70/S70/V70/V71 USBHS are the same USB
 * controller. The device register block has identical offsets and identical
 * bitfield positions and encodings in both; only the macro prefix differs.
 * This header maps the UOTGHS names onto the USBHS names used by
 * udc_sam_usbhs.c and supplies the positional and shift helpers that the
 * older ASF UOTGHS header does not define.
 *
 * SAM3X specifics that are not a plain rename:
 *   - UOTGHS_CTRL_OTGPADE must be set to power the OTG pad, otherwise
 *     clearing UOTGHS_DEVCTRL_DETACH does not pull up D+.
 *   - UOTGHS_CTRL_UIDE must be clear for UOTGHS_CTRL_UIMOD to select device
 *     mode. It is set after reset, so UOTGHS_CTRL must be written as a whole
 *     word and never read-modify-written.
 *   - The USB_48M gate is PMC_SCER_UOTGCLK, not PMC_SCER_USBCLK.
 */

