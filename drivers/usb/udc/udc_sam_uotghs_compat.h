/*
 * Positional definitions absent from the ASF UOTGHS header. Values taken from
 * the SAM3X datasheet register descriptions (UOTGHS_DEVEPT bits 8:0 EPENx and
 * 24:16 EPRSTx, UOTGHS_DEVISR bits 21:12 PEP_x).
 */
#define USBHS_DEVEPT_EPEN0_Pos			0
#define USBHS_DEVEPT_EPRST0_Pos			16
#define USBHS_DEVISR_PEP_0_Pos			12
#define USBHS_DEVIDR_PEP_0_Pos			12
#define USBHS_DEVIER_PEP_0_Pos			12
#define USBHS_DEVISR_PEP__Msk			(0x3ffu << USBHS_DEVISR_PEP_0_Pos)
#define USBHS_SR_SPEED_HIGH_SPEED_Val		1

/* Shift helpers absent from the ASF UOTGHS header */
#define USBHS_DEVEPTCFG_EPBK(value)					\
	(UOTGHS_DEVEPTCFG_EPBK_Msk &					\
	 ((value) << UOTGHS_DEVEPTCFG_EPBK_Pos))
#define USBHS_DEVEPTCFG_EPSIZE(value)					\
	(UOTGHS_DEVEPTCFG_EPSIZE_Msk &					\
	 ((value) << UOTGHS_DEVEPTCFG_EPSIZE_Pos))
#define USBHS_DEVEPTCFG_EPTYPE(value)					\
	(UOTGHS_DEVEPTCFG_EPTYPE_Msk &					\
	 ((value) << UOTGHS_DEVEPTCFG_EPTYPE_Pos))

/* The USB_48M clock gate is named after the OTG controller on SAM3X */
#define PMC_SCER_USBCLK				PMC_SCER_UOTGCLK
#define PMC_SCDR_USBCLK				PMC_SCDR_UOTGCLK

#endif /* ZEPHYR_DRIVERS_USB_UDC_UDC_SAM_UOTGHS_COMPAT_H_ */
